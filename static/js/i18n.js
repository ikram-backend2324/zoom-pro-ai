function getLang(){const s=localStorage.getItem(I18N_KEY);if(s&&I18N[s])return s;const n=(navigator.language||"en").slice(0,2);if(n==="ru")return "ru";if(n==="uz")return "uz";return "en";}
function t(key,lang){const L=lang||getLang();return (I18N[L]&&I18N[L][key])||I18N.en[key]||key;}
function applyLang(lang){const d=I18N[lang]||I18N.en;document.documentElement.lang=lang==="kaa"?"kaa":lang;
document.querySelectorAll("[data-i18n]").forEach(el=>{const k=el.getAttribute("data-i18n");if(d[k]!==undefined)el.textContent=d[k];});
document.querySelectorAll("[data-i18n-html]").forEach(el=>{const k=el.getAttribute("data-i18n-html");if(d[k]!==undefined)el.innerHTML=d[k];});
document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{const k=el.getAttribute("data-i18n-placeholder");if(d[k]!==undefined)el.placeholder=d[k];});
document.querySelectorAll("[data-i18n-title]").forEach(el=>{const k=el.getAttribute("data-i18n-title");if(d[k]!==undefined)el.title=d[k];});
const meta=LANG_ORDER.find(l=>l.code===lang)||LANG_ORDER[0];const cur=document.getElementById("langCurrent");if(cur)cur.textContent=meta.short;
document.querySelectorAll(".lang-option").forEach(o=>o.classList.toggle("active",o.dataset.lang===lang));
window.dispatchEvent(new CustomEvent("langchange",{detail:{lang}}));}
function setLang(lang){if(!I18N[lang])return;localStorage.setItem(I18N_KEY,lang);applyLang(lang);}
window.t=t;window.getLang=getLang;window.setLang=setLang;window.LANG_ORDER=LANG_ORDER;
function initLangSwitcher(){const menu=document.getElementById("langMenu");
if(menu&&!menu.dataset.built){menu.dataset.built="1";LANG_ORDER.forEach(l=>{const o=document.createElement("button");o.className="lang-option";o.dataset.lang=l.code;o.innerHTML='<span class="lang-flag">'+l.flag+'</span><span class="lang-text">'+I18N[l.code]["lang.name"]+'</span><span class="lang-check">✓</span>';o.addEventListener("click",()=>{setLang(l.code);document.getElementById("langSwitch")?.classList.remove("open");});menu.appendChild(o);});}
const tg=document.getElementById("langToggle"),wr=document.getElementById("langSwitch");
if(tg&&wr){tg.addEventListener("click",e=>{e.stopPropagation();wr.classList.toggle("open");});document.addEventListener("click",()=>wr.classList.remove("open"));}
applyLang(getLang());}
if(document.readyState==="loading"){document.addEventListener("DOMContentLoaded",initLangSwitcher);}else{initLangSwitcher();}
